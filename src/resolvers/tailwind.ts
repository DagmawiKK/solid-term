function lookupPatternClass(base: string): Partial<StyleTokens> | undefined {
  const textMatch = base.match(/^text-([a-z]+)-(\d+)$/)
  if (textMatch) {
    const hex = TAILWIND_PALETTE[textMatch[1]]?.[parseInt(textMatch[2], 10)]
    if (hex) return { fg: { hex } }
  }
  const bgMatch = base.match(/^bg-([a-z]+)-(\d+)$/)
  if (bgMatch) {
    const hex = TAILWIND_PALETTE[bgMatch[1]]?.[parseInt(bgMatch[2], 10)]
    if (hex) return { bg: { hex } }
  }
  return undefined
}

const BREAKPOINTS: Record<string, number> = {
  sm: 60, md: 80, lg: 100, xl: 120, '2xl': 140,
}

export function tailwind(): ClassResolver {
  return (classes: string[], options: ClassResolverOptions): StyleTokens => {
    const tokens: StyleTokens = {}

    for (const cls of classes) {
      const [prefix, base] = splitResponsive(cls)

      if (prefix && options.width < (BREAKPOINTS[prefix] ?? 80)) continue

      if (cls.startsWith('dark:') && options.theme !== 'dark') continue

      const lookupKey = cls.startsWith('dark:') ? cls.slice(5) : base
      const entry = TAILWIND_MAP[lookupKey] ?? lookupPatternClass(lookupKey)
      if (!entry) continue

      if (entry.fg !== undefined) tokens.fg = entry.fg
      if (entry.bg !== undefined) tokens.bg = entry.bg
      if (entry.bold !== undefined) tokens.bold = entry.bold
      if (entry.italic !== undefined) tokens.italic = entry.italic
      if (entry.underline !== undefined) tokens.underline = entry.underline
      if (entry.strikethrough !== undefined) tokens.strikethrough = entry.strikethrough
    }

    return tokens
  }
}
